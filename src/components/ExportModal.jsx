import React, { useState } from 'react';
import { X, Download, Copy, Check, FileSpreadsheet, MessageSquare, FileText, Code2 } from 'lucide-react';

export default function ExportModal({ isOpen, onClose, data }) {
  if (!isOpen || !data) return null;

  const [activeFormat, setActiveFormat] = useState('jira');
  const [copied, setCopied] = useState(false);

  const { title, executiveSummary, decisions = [], actionItems = [], risks = [], followUps = [] } = data;

  // Generate Jira CSV
  const generateJiraCSV = () => {
    const headers = ["Summary", "Issue Type", "Priority", "Assignee", "Due Date", "Component", "Description"];
    const rows = actionItems.map(item => [
      `"${item.task.replace(/"/g, '""')}"`,
      "Task",
      item.priority === 'P0' ? 'Highest' : item.priority === 'P1' ? 'High' : 'Medium',
      `"${item.owner}"`,
      item.dueDate,
      item.category,
      `"Generated by MeetingPulse AI from meeting '${title}'. Jira Key: ${item.jiraKey}"`
    ]);
    return [headers.join(','), ...rows.map(r => r.join(','))].join('\n');
  };

  // Generate Slack Digest
  const generateSlackDigest = () => {
    return `📢 *Meeting Digest: ${title}*
_${executiveSummary}_

*🏆 Key Decisions Made:*
${decisions.map(d => `• *${d.decision}* (Lead: @${d.owner.split(' ')[0]}) — _${d.rationale}_`).join('\n')}

*⚡ Action Items & Assignees:*
${actionItems.map(a => `• [${a.priority}] *${a.task}* → @${a.owner} (Due: ${a.dueDate}) [${a.jiraKey}]`).join('\n')}

${risks.length > 0 ? `*⚠️ Blockers & Risks Flagged:*\n${risks.map(r => `• *${r.risk}* (${r.severity}): ${r.mitigation}`).join('\n')}\n` : ''}
*🔗 Next Steps:* Check Confluence for full architectural details.`;
  };

  // Generate Confluence Markdown
  const generateMarkdownDoc = () => {
    return `# Meeting Minutes: ${title}
**Date:** ${new Date().toISOString().split('T')[0]}  
**Status:** Generated via MeetingPulse AI TPM Copilot  

## 1. Executive Summary
${executiveSummary}

## 2. Key Decisions & Architecture Choices
| Decision | Rationale | Impacted Teams | Owner |
| :--- | :--- | :--- | :--- |
${decisions.map(d => `| **${d.decision}** | ${d.rationale} | ${(d.impactedTeams || []).join(', ')} | ${d.owner} |`).join('\n')}

## 3. Action Items & Workstream Allocation
| Key | Task | Priority | Domain | Owner | Due Date | Status |
| :--- | :--- | :--- | :--- | :--- | :--- | :--- |
${actionItems.map(a => `| ${a.jiraKey} | ${a.task} | **${a.priority}** | ${a.category} | ${a.owner} | ${a.dueDate} | ${a.status} |`).join('\n')}

## 4. Risks & Mitigations
${risks.map(r => `- **${r.risk}** (${r.severity} Severity): ${r.mitigation}`).join('\n')}

## 5. Follow-Ups & Open Topics
${followUps.map(f => `- ${f}`).join('\n')}
`;
  };

  const handleCopy = (content) => {
    navigator.clipboard.writeText(content);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = (filename, content, mimeType) => {
    const blob = new Blob([content], { type: mimeType });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = filename;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };

  let displayContent = '';
  if (activeFormat === 'jira') displayContent = generateJiraCSV();
  else if (activeFormat === 'slack') displayContent = generateSlackDigest();
  else if (activeFormat === 'markdown') displayContent = generateMarkdownDoc();
  else if (activeFormat === 'json') displayContent = JSON.stringify(data, null, 2);

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-950/80 backdrop-blur-sm animate-fadeIn">
      <div className="bg-slate-900 border border-slate-800 rounded-2xl w-full max-w-3xl shadow-2xl overflow-hidden flex flex-col max-h-[90vh]">
        {/* Header */}
        <div className="px-6 py-4 border-b border-slate-800 flex items-center justify-between bg-slate-950/50">
          <div className="flex items-center space-x-2">
            <Download className="w-5 h-5 text-emerald-400" />
            <h3 className="font-bold text-base text-white">Export Meeting Artifacts</h3>
          </div>
          <button
            onClick={onClose}
            className="p-1 rounded-lg text-slate-400 hover:text-white hover:bg-slate-800 transition"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Format Selector */}
        <div className="flex border-b border-slate-800 bg-slate-950/30 px-6 pt-3 gap-2">
          <button
            onClick={() => setActiveFormat('jira')}
            className={`pb-3 px-3 text-xs font-semibold flex items-center gap-1.5 border-b-2 transition ${
              activeFormat === 'jira'
                ? 'border-emerald-500 text-emerald-400'
                : 'border-transparent text-slate-400 hover:text-slate-200'
            }`}
          >
            <FileSpreadsheet className="w-4 h-4" />
            <span>Jira CSV Export</span>
          </button>

          <button
            onClick={() => setActiveFormat('slack')}
            className={`pb-3 px-3 text-xs font-semibold flex items-center gap-1.5 border-b-2 transition ${
              activeFormat === 'slack'
                ? 'border-emerald-500 text-emerald-400'
                : 'border-transparent text-slate-400 hover:text-slate-200'
            }`}
          >
            <MessageSquare className="w-4 h-4" />
            <span>Slack Digest</span>
          </button>

          <button
            onClick={() => setActiveFormat('markdown')}
            className={`pb-3 px-3 text-xs font-semibold flex items-center gap-1.5 border-b-2 transition ${
              activeFormat === 'markdown'
                ? 'border-emerald-500 text-emerald-400'
                : 'border-transparent text-slate-400 hover:text-slate-200'
            }`}
          >
            <FileText className="w-4 h-4" />
            <span>Confluence Markdown</span>
          </button>

          <button
            onClick={() => setActiveFormat('json')}
            className={`pb-3 px-3 text-xs font-semibold flex items-center gap-1.5 border-b-2 transition ${
              activeFormat === 'json'
                ? 'border-emerald-500 text-emerald-400'
                : 'border-transparent text-slate-400 hover:text-slate-200'
            }`}
          >
            <Code2 className="w-4 h-4" />
            <span>Raw JSON</span>
          </button>
        </div>

        {/* Content Box */}
        <div className="p-6 flex-1 overflow-y-auto">
          <pre className="p-4 bg-slate-950 rounded-xl border border-slate-800 text-xs text-slate-300 font-mono overflow-x-auto whitespace-pre leading-relaxed max-h-80">
            {displayContent}
          </pre>
        </div>

        {/* Footer Actions */}
        <div className="px-6 py-4 border-t border-slate-800 bg-slate-950/50 flex items-center justify-between">
          <span className="text-xs text-slate-400">
            {activeFormat === 'jira' && 'Ready for Jira -> Project Settings -> Import CSV'}
            {activeFormat === 'slack' && 'Formatted with Slack-native markdown tags'}
            {activeFormat === 'markdown' && 'Ready for Confluence, Notion, or GitHub Wiki'}
            {activeFormat === 'json' && 'Structured schema ready for webhook payloads'}
          </span>

          <div className="flex items-center space-x-2">
            <button
              onClick={() => handleCopy(displayContent)}
              className="px-4 py-2 rounded-xl text-xs font-semibold bg-slate-800 hover:bg-slate-700 text-slate-200 border border-slate-700 flex items-center gap-1.5 transition"
            >
              {copied ? <Check className="w-4 h-4 text-emerald-400" /> : <Copy className="w-4 h-4" />}
              <span>{copied ? 'Copied!' : 'Copy to Clipboard'}</span>
            </button>

            {activeFormat === 'jira' && (
              <button
                onClick={() => handleDownload('jira-tasks-export.csv', displayContent, 'text/csv')}
                className="px-4 py-2 rounded-xl text-xs font-bold bg-emerald-500 hover:bg-emerald-400 text-slate-950 flex items-center gap-1.5 transition shadow-lg shadow-emerald-500/20"
              >
                <Download className="w-4 h-4" />
                <span>Download CSV</span>
              </button>
            )}

            {activeFormat === 'markdown' && (
              <button
                onClick={() => handleDownload('meeting-minutes.md', displayContent, 'text/markdown')}
                className="px-4 py-2 rounded-xl text-xs font-bold bg-emerald-500 hover:bg-emerald-400 text-slate-950 flex items-center gap-1.5 transition shadow-lg shadow-emerald-500/20"
              >
                <Download className="w-4 h-4" />
                <span>Download .MD</span>
              </button>
            )}
          </div>
        </div>
      </div>
    </div>
  );
}
